/*********************************************************************
* 文件：touch.h
* 说明：FT5336 电容触摸驱动（I2C3，地址 0x70）
*       采用主循环轮询方式，不依赖 EXTI，简单可靠。
*********************************************************************/
#ifndef TOUCH_H
#define TOUCH_H

#include <stdint.h>

/* 初始化；返回 1 表示检测到触摸芯片并可用 */
uint8_t touch_init(void);

/* 读取触摸点；返回 1 表示当前有触摸，坐标写入 x/y
   坐标范围与面板一致：x 0..479，y 0..271 */
uint8_t touch_read(uint16_t *x, uint16_t *y);

/* 初始化失败时的诊断码：0=无错误，1=总线错误，2=无应答(地址/上电)，
   3=超时(总线锁死/无上拉)，4=其他 */
uint8_t touch_error(void);

#endif /* TOUCH_H */